"""DDS <-> PNG for the UI textures (stdlib only). Reads DXT1/DXT3/DXT5 and 32-bit RGB(A); writes PNG, and writes DDS back
as uncompressed A8R8G8B8 (D3DX loads it like the original; only the file grows), mip levels regenerated by 2x2 averaging.
usage: fsdds.py topng <in.dds> <out.png>  |  fsdds.py todds <in.png> <like.dds> <out.dds>"""
import struct, zlib, sys
def _565(c): return ((c >> 11) & 31) * 255 // 31, ((c >> 5) & 63) * 255 // 63, (c & 31) * 255 // 31
def _color_block(b, o, dxt1):
    c0, c1, bits = struct.unpack_from('<HHI', b, o); p0, p1 = _565(c0), _565(c1)
    if c0 > c1 or not dxt1: pal = [p0 + (255,), p1 + (255,), tuple((2 * a + c) // 3 for a, c in zip(p0, p1)) + (255,), tuple((a + 2 * c) // 3 for a, c in zip(p0, p1)) + (255,)]
    else: pal = [p0 + (255,), p1 + (255,), tuple((a + c) // 2 for a, c in zip(p0, p1)) + (255,), (0, 0, 0, 0)]
    return [pal[(bits >> 2 * i) & 3] for i in range(16)]
def _alpha5(b, o):
    a0, a1 = b[o], b[o + 1]; bits = int.from_bytes(b[o + 2:o + 8], 'little')
    pal = [a0, a1] + ([((6 - i) * a0 + (i + 1) * a1) // 7 for i in range(6)] if a0 > a1 else [((4 - i) * a0 + (i + 1) * a1) // 5 for i in range(4)] + [0, 255])
    return [pal[(bits >> 3 * i) & 7] for i in range(16)]
def read(path):
    """-> (w, h, rgba bytes, header info) of mip 0"""
    d = open(path, 'rb').read(); assert d[:4] == b'DDS ', path
    h, w = struct.unpack_from('<II', d, 12); mips = max(1, struct.unpack_from('<I', d, 28)[0]); pf_flags, four, bits = struct.unpack_from('<I4sI', d, 80)
    rm, gm, bm, am = struct.unpack_from('<IIII', d, 92); o = 128; px = bytearray(w * h * 4)
    if pf_flags & 4:
        bs = 8 if four == b'DXT1' else 16
        for by in range(0, h, 4):
            for bx in range(0, w, 4):
                if four == b'DXT1': cols = _color_block(d, o, True)
                else:
                    cols = _color_block(d, o + 8, False)
                    al = [((int.from_bytes(d[o:o + 8], 'little') >> 4 * i) & 15) * 17 for i in range(16)] if four == b'DXT3' else _alpha5(d, o)
                    cols = [c[:3] + (a,) for c, a in zip(cols, al)]
                for i, c in enumerate(cols):
                    x, y = bx + i % 4, by + i // 4
                    if x < w and y < h: px[(y * w + x) * 4:(y * w + x) * 4 + 4] = bytes(c)
                o += bs
    else:
        assert bits == 32, (path, bits)
        sh = lambda m: (m & -m).bit_length() - 1 if m else 0
        for i in range(w * h):
            v, = struct.unpack_from('<I', d, o + 4 * i)
            px[4 * i:4 * i + 4] = bytes(((v & rm) >> sh(rm), (v & gm) >> sh(gm), (v & bm) >> sh(bm), ((v & am) >> sh(am)) if am else 255))
    return w, h, bytes(px), mips
def write_png(path, w, h, rgba):
    raw = b''.join(b'\0' + rgba[y * w * 4:(y + 1) * w * 4] for y in range(h))
    ch = lambda t, b: struct.pack('>I', len(b)) + t + b + struct.pack('>I', zlib.crc32(t + b))
    open(path, 'wb').write(b'\x89PNG\r\n\x1a\n' + ch(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0)) + ch(b'IDAT', zlib.compress(raw, 9)) + ch(b'IEND', b''))
def read_png(path):
    """8-bit RGBA or RGB, non-interlaced PNG -> (w, h, rgba)"""
    d = open(path, 'rb').read(); assert d[:8] == b'\x89PNG\r\n\x1a\n'; p, idat = 8, b''
    while p < len(d):
        n, = struct.unpack_from('>I', d, p); t = d[p + 4:p + 8]; b = d[p + 8:p + 8 + n]; p += 12 + n
        if t == b'IHDR': w, h, bd, ct, _, _, il = struct.unpack('>IIBBBBB', b); assert bd == 8 and ct in (2, 6) and not il, 'PNG must be 8-bit RGB/RGBA'
        elif t == b'IDAT': idat += b
    bpp = 4 if ct == 6 else 3; raw = zlib.decompress(idat); stride = w * bpp; out = bytearray(); prev = bytearray(stride); p = 0
    for _ in range(h):
        f = raw[p]; line = bytearray(raw[p + 1:p + 1 + stride]); p += 1 + stride
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0; b = prev[i]; c = prev[i - bpp] if i >= bpp else 0
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + b) & 255
            elif f == 3: line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4: pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c); line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        out += line if bpp == 4 else b''.join(bytes(line[i:i + 3]) + b'\xff' for i in range(0, stride, 3)); prev = line
    return w, h, bytes(out)
def write_dds(path, w, h, rgba, mips):
    hdr = struct.pack('<4sIIIIIII44xIIIIIIII', b'DDS ', 124, 0x1 | 0x2 | 0x4 | 0x8 | 0x1000 | (0x20000 if mips > 1 else 0), h, w, w * 4, 0, mips,
                      32, 0x41, 0, 32, 0x00ff0000, 0x0000ff00, 0x000000ff, 0xff000000) + struct.pack('<IIIII', 0x1000 | (0x400008 if mips > 1 else 0), 0, 0, 0, 0)
    body, cw, chh, cur = b'', w, h, rgba
    for m in range(mips):
        body += b''.join(bytes((cur[i + 2], cur[i + 1], cur[i], cur[i + 3])) for i in range(0, len(cur), 4))   # RGBA -> BGRA
        if cw == 1 and chh == 1: break
        nw, nh = max(1, cw // 2), max(1, chh // 2); nxt = bytearray(nw * nh * 4)
        for y in range(nh):
            for x in range(nw):
                for k in range(4):
                    s = [cur[((min(2 * y + dy, chh - 1)) * cw + min(2 * x + dx, cw - 1)) * 4 + k] for dy in (0, 1) for dx in (0, 1)]
                    nxt[(y * nw + x) * 4 + k] = sum(s) // 4
        cw, chh, cur = nw, nh, bytes(nxt)
    assert len(hdr) == 128; open(path, 'wb').write(hdr + body)
if __name__ == '__main__':
    if sys.argv[1] == 'topng': w, h, px, _ = read(sys.argv[2]); write_png(sys.argv[3], w, h, px)
    elif sys.argv[1] == 'todds':
        w, h, px = read_png(sys.argv[2]); lw, lh, _, mips = read(sys.argv[3]); assert (w, h) == (lw, lh), f'size {w}x{h} != original {lw}x{lh}'
        write_dds(sys.argv[4], w, h, px, mips)
