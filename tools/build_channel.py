"""Thai channel v2 on the table the engine really loads: Bin/Code/BIG2GB.idx (FS3.exe references it; b2g.dat is never loaded).
BIG2GB.idx: 65,536 x 2 B; index = the two text bytes read as a little-endian WORD (lead | trail<<8); the stored 2 bytes are the GBK bytes in order.
Keeps the 87 Big5 channel codes of the user's FS3_TH_map.txt, assigns new reserved GBK pairs from the GBK user-defined area AAA1-AFFE
(which BIG2GB.idx never outputs). Also adds the KEY codes for proxy-side text expansion:
Big5 user-defined FA41 = key marker (-> U+E000), FA42.. = 128 digit codes (-> U+E100+d); FB41.. = 128 one-char SHORT keys
(-> U+E200+id, for slots of 2-5 bytes); dialog text never uses lead bytes FA/FB [V].
Writes <out>/FS3_TH_map.txt and <out>/FS3Bin.dat (= original FS3Bin.dat.bak with only BIG2GB.idx patched).
usage: build_channel.py <game_copy> <old_map> <out_dir>"""
import os, sys, hashlib
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fszip, thaichan
game, oldmap, out = sys.argv[1:4]
t2b = {k: v for k, v in thaichan.load_map(oldmap)[0].items() if 0x0E00 <= ord(k) <= 0x0E7F}   # Thai letters only (re-runnable on a v3 map)
src = f'{game}/Pack/FS3Bin.dat.bak'; raw = open(src, 'rb').read(); z = fszip.open_fszip_bytes(raw)
idx = bytearray(z.read('Bin/Code/BIG2GB.idx'))
w = lambda c: ((c & 0xff) << 8) | (c >> 8)
produced = {bytes(idx[i*2:i*2+2]) for i in range(0x10000)}
free = [bytes([l, t]) for l in range(0xAA, 0xB0) for t in range(0xA1, 0xFF) if bytes([l, t]) not in produced]
assert len(free) >= len(t2b), len(free)
lines = ['# Thai channel v2 (BIG2GB.idx). GBKPAIR UNICODE  # char via big5 CODE   -- generated by tools/build_channel.py']
KEY_MARK = 0xE000; KEY_DIG = 0xE100; NDIG = 128; KEY_SHORT = 0xE200; NSHORT = 128
keycodes = [0xFA00 | t for t in list(range(0x41, 0x7F)) + list(range(0xA1, 0xFF))][:1 + NDIG]   # never trail 0x40 ('@') or 0x2A ('*')
shortcodes = [0xFB00 | t for t in list(range(0x41, 0x7F)) + list(range(0xA1, 0xFF))][:NSHORT]
entries = sorted(t2b.items(), key=lambda kv: kv[0]) + [(chr(KEY_MARK), keycodes[0])] + [(chr(KEY_DIG + d), keycodes[1 + d]) for d in range(NDIG)]         + [(chr(KEY_SHORT + d), shortcodes[d]) for d in range(NSHORT)]
assert len(free) >= len(entries), (len(free), len(entries))
newpair = {}
for (ch, b5), g in zip(entries, free):
    assert idx[w(b5)*2:w(b5)*2+2] != g
    idx[w(b5)*2:w(b5)*2+2] = g; newpair[b5] = g
    tag = 'KEY marker' if ord(ch) == KEY_MARK else f'KEY short {ord(ch) - KEY_SHORT}' if ord(ch) >= KEY_SHORT         else f'KEY digit {ord(ch) - KEY_DIG}' if ord(ch) >= KEY_DIG else f'U+{ord(ch):04X}'
    lines.append(f'{g.hex().upper()} {ord(ch):04X}  # {tag} via big5 {b5:04X}')
os.makedirs(out, exist_ok=True)
open(f'{out}/FS3_TH_map.txt', 'w', encoding='ascii').write('\n'.join(lines) + '\n')
blob = fszip.write_like(z, raw, replace={'Bin/Code/BIG2GB.idx': bytes(idx)})
open(f'{out}/FS3Bin.dat', 'wb').write(blob)
# verify: CRCs, only BIG2GB.idx differs from the original, channel round trip through the patched table
z2 = fszip.open_fszip_bytes(blob); assert z2.testzip() is None
diff = [i.filename for i in z.infolist() if z.read(i.filename) != z2.read(i.filename)]; assert diff == ['Bin/Code/BIG2GB.idx'], diff
idx2 = z2.read('Bin/Code/BIG2GB.idx'); m2, pair2 = thaichan.load_map(f'{out}/FS3_TH_map.txt')
for ch, b5 in entries:
    g = idx2[w(b5)*2:w(b5)*2+2]; assert int.from_bytes(g, 'big') == pair2[b5] and m2[ch] == b5
others = {bytes(idx2[i*2:i*2+2]) for i in range(0x10000) if i not in {w(b) for _, b in entries}}
assert not (others & set(newpair.values())), 'a reserved pair is produced by a non-channel code'
print(f'{len(t2b)} Thai + {1 + NDIG + NSHORT} key codes -> GBK UDA pairs {min(newpair.values()).hex()}..{max(newpair.values()).hex()}; FS3Bin.dat {len(blob)} B sha256 {hashlib.sha256(blob).hexdigest()[:16]}; changed: {diff}')
